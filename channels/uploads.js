import { createHash, randomBytes } from 'node:crypto';
import { BridgeError } from '../router/common.js';
import { MAX_MEDIA_BYTES, mediaName, mediaMime, validateMedia } from './media.js';
import { validateToolValue } from './tool-schema.js';

export const UPLOAD_CHUNK_BYTES = 256 * 1024;
export const UPLOAD_RPC_BYTES = 393216;
const hash = (value) => createHash('sha256').update(value).digest('hex');
const schema = (properties, required = Object.keys(properties)) => ({
  type: 'object',
  properties,
  required,
  additionalProperties: false,
});
const messageId = { type: 'string', minLength: 1, maxLength: 256 };
const uploadId = { type: 'string', pattern: '^upload_[a-f0-9]{48}$', minLength: 55, maxLength: 55 };
const key = { type: 'string', minLength: 1, maxLength: 128 };
const receipt = schema({
  message_id: messageId,
  upload_id: uploadId,
  received_bytes: { type: 'integer', minimum: 0, maximum: MAX_MEDIA_BYTES },
  complete: { type: 'boolean' },
});
const reply = schema({
  message_id: messageId,
  status: {
    type: 'string',
    enum: ['none', 'pending', 'processing', 'sent', 'expired', 'dead', 'cancelled', 'uncertain'],
  },
});

export function uploadDefinitions(channel, mediaTypes = ['image', 'audio', 'file']) {
  const tool = (name, description, inputSchema, outputSchema) => ({
    name,
    description,
    inputSchema,
    outputSchema,
    annotations: {
      readOnlyHint: false,
      destructiveHint: false,
      idempotentHint: true,
      openWorldHint: false,
    },
  });
  return [
    tool(
      `begin_${channel}_attachment_upload`,
      'Begin a bounded encrypted upload for a file generated by the original agent, bound to this authorized source message. Read the file programmatically and upload chunks; do not copy Base64 into conversation text. No URL, filesystem path or recipient is accepted. The upload does not send anything.',
      schema({
        message_id: messageId,
        type: { type: 'string', enum: mediaTypes },
        name: {
          type: 'string',
          minLength: 1,
          maxLength: ['lark', 'qq'].includes(channel) ? 128 : 255,
        },
        mime_type: { type: 'string', maxLength: 128 },
        size: { type: 'integer', minimum: 1, maximum: MAX_MEDIA_BYTES },
        sha256: { type: 'string', pattern: '^[a-f0-9]{64}$', minLength: 64, maxLength: 64 },
        idempotency_key: key,
      }),
      receipt,
    ),
    tool(
      `append_${channel}_attachment_upload`,
      'Append one canonical Base64 chunk, at most 256 KiB decoded, at the exact received byte offset. Identical chunk retries are idempotent. The source must remain authorized. No send occurs.',
      schema({
        upload_id: uploadId,
        offset: { type: 'integer', minimum: 0, maximum: MAX_MEDIA_BYTES },
        data: { type: 'string', minLength: 4, maxLength: 349528 },
      }),
      receipt,
    ),
    tool(
      `finish_${channel}_attachment_upload`,
      'Verify total size, SHA-256 and media format before marking the encrypted upload complete. It still does not send the file.',
      schema({ upload_id: uploadId }),
      receipt,
    ),
    {
      ...tool(
        `reply_${channel}_uploaded_attachment`,
        'Queue the completed upload as the one final reply to its original source. The existing media format, authorization and reply-window limits apply. Reuse the same key; never retry an uncertain send with a new key.',
        schema({ message_id: messageId, upload_id: uploadId, idempotency_key: key }),
        reply,
      ),
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: true,
      },
    },
  ];
}
export const isUploadTool = (channel, name) =>
  uploadDefinitions(channel).some((tool) => tool.name === name);
export function validateUploadArguments(channel, name, args, mediaTypes) {
  try {
    const tool = uploadDefinitions(channel, mediaTypes).find((tool) => tool.name === name);
    if (!tool) throw Error();
    validateToolValue(args, tool.inputSchema);
    if (args.name !== undefined) mediaName(args.name);
    if (args.mime_type !== undefined) mediaMime(args.mime_type);
    return { ...args };
  } catch {
    throw new BridgeError('Invalid source-bound upload arguments');
  }
}
export function projectUploadResult(channel, call, result, mediaTypes) {
  const tool = uploadDefinitions(channel, mediaTypes).find((tool) => tool.name === call.name);
  if (!tool || result?.isError !== false) throw Error('Invalid upload result');
  validateToolValue(result.structuredContent, tool.outputSchema);
  const value = result.structuredContent;
  if (
    (call.arguments.message_id !== undefined && value.message_id !== call.arguments.message_id) ||
    (call.arguments.upload_id !== undefined &&
      value.upload_id !== undefined &&
      value.upload_id !== call.arguments.upload_id)
  )
    throw Error('Unbound upload result');
  return structuredClone(value);
}

export class SourceUploads {
  constructor({ channel, db, seal, open, authorize, clock = Date.now, mediaTypes }) {
    Object.assign(this, { channel, db, seal, open, authorize, clock, mediaTypes });
    db.exec(`CREATE TABLE IF NOT EXISTS dotbridge_uploads(id TEXT PRIMARY KEY,message_id TEXT NOT NULL,request_hash TEXT UNIQUE NOT NULL,digest TEXT NOT NULL,payload TEXT NOT NULL,received INTEGER NOT NULL,state TEXT NOT NULL,expires INTEGER NOT NULL,reply_key TEXT);
      CREATE TABLE IF NOT EXISTS dotbridge_upload_chunks(upload_id TEXT NOT NULL,offset INTEGER NOT NULL,payload TEXT NOT NULL,digest TEXT NOT NULL,PRIMARY KEY(upload_id,offset));`);
  }
  tx(action) {
    this.db.exec('BEGIN IMMEDIATE');
    try {
      const result = action();
      this.db.exec('COMMIT');
      return result;
    } catch (error) {
      this.db.exec('ROLLBACK');
      throw error;
    }
  }
  row(id) {
    const row = this.db.prepare('SELECT * FROM dotbridge_uploads WHERE id=?').get(id);
    if (!row || row.expires <= this.clock())
      throw new BridgeError('Upload is unavailable', { code: -32012, status: 403 });
    this.authorize(row.message_id);
    return row;
  }
  status(row) {
    return {
      message_id: row.message_id,
      upload_id: row.id,
      received_bytes: row.received,
      complete: ['complete', 'consumed'].includes(row.state),
    };
  }
  purge() {
    this.db
      .prepare(
        'DELETE FROM dotbridge_upload_chunks WHERE upload_id IN (SELECT id FROM dotbridge_uploads WHERE expires<=?)',
      )
      .run(this.clock());
    this.db.prepare('DELETE FROM dotbridge_uploads WHERE expires<=?').run(this.clock());
  }
  data(row) {
    const chunks = this.db
      .prepare(
        'SELECT offset,payload FROM dotbridge_upload_chunks WHERE upload_id=? ORDER BY offset',
      )
      .all(row.id);
    const buffers = [];
    let offset = 0;
    try {
      for (const chunk of chunks) {
        if (chunk.offset !== offset) throw new BridgeError('Upload has a missing chunk');
        const bytes = Buffer.from(
          this.open(chunk.payload, `upload-chunk:${row.id}:${chunk.offset}`),
          'base64',
        );
        buffers.push(bytes);
        offset += bytes.length;
      }
      const metadata = this.open(row.payload, `upload:${row.id}`);
      if (offset !== metadata.size) throw new BridgeError('Upload is incomplete');
      const bytes = Buffer.concat(buffers);
      if (hash(bytes) !== metadata.sha256) {
        bytes.fill(0);
        throw new BridgeError('Uploaded file checksum differs');
      }
      try {
        validateMedia({
          type: metadata.type,
          data: bytes,
          mimeType: metadata.mime_type,
          name: metadata.name,
        });
      } catch (error) {
        bytes.fill(0);
        throw error;
      }
      return { bytes, metadata };
    } finally {
      for (const bytes of buffers) bytes.fill(0);
    }
  }
  call(name, raw, { queue, getReplyStatus } = {}) {
    const args = validateUploadArguments(this.channel, name, raw, this.mediaTypes);
    this.purge();
    if (name === `begin_${this.channel}_attachment_upload`) {
      const source = this.authorize(args.message_id);
      const requestHash = hash(args.message_id + ':' + args.idempotency_key),
        digest = hash(JSON.stringify(args));
      return this.tx(() => {
        const previous = this.db
          .prepare('SELECT * FROM dotbridge_uploads WHERE request_hash=?')
          .get(requestHash);
        if (previous) {
          if (previous.digest !== digest)
            throw new BridgeError('Upload key already has different metadata', {
              code: -32013,
              status: 409,
            });
          return this.status(previous);
        }
        if (this.db.prepare('SELECT count(*) AS n FROM dotbridge_uploads').get().n >= 32)
          throw new BridgeError('Upload capacity reached', { code: -32013, status: 429 });
        const id = 'upload_' + randomBytes(24).toString('hex');
        const expiry = Math.min(source.expires ?? source.replyDeadline, this.clock() + 600000);
        if (!Number.isSafeInteger(expiry) || expiry <= this.clock())
          throw new BridgeError('Source reply window expired');
        this.db
          .prepare("INSERT INTO dotbridge_uploads VALUES (?,?,?,?,?,0,'pending',?,NULL)")
          .run(id, args.message_id, requestHash, digest, this.seal(args, `upload:${id}`), expiry);
        return this.status(this.row(id));
      });
    }
    const row = this.row(args.upload_id);
    if (args.message_id !== undefined && args.message_id !== row.message_id)
      throw new BridgeError('Upload belongs to another source', { code: -32012, status: 403 });
    if (name === `append_${this.channel}_attachment_upload`) return this.append(row, args);
    if (name === `finish_${this.channel}_attachment_upload`) {
      if (row.state === 'pending') {
        const { bytes } = this.data(row);
        bytes.fill(0);
        this.db.prepare("UPDATE dotbridge_uploads SET state='complete' WHERE id=?").run(row.id);
      }
      return this.status(this.row(row.id));
    }
    if (typeof queue !== 'function' || typeof getReplyStatus !== 'function')
      throw Error('Upload reply integration unavailable');
    if (row.state === 'consumed') {
      if (row.reply_key !== args.idempotency_key)
        throw new BridgeError('Completed upload uses a different reply key', {
          code: -32013,
          status: 409,
        });
      return getReplyStatus(row.message_id);
    }
    if (row.state !== 'complete') throw new BridgeError('Finish the upload before replying');
    const { bytes, metadata } = this.data(row);
    try {
      this.authorize(row.message_id);
      const result = queue(row.message_id, {
        ...metadata,
        data: bytes.toString('base64'),
        idempotency_key: args.idempotency_key,
      });
      this.db
        .prepare("UPDATE dotbridge_uploads SET state='consumed',reply_key=? WHERE id=?")
        .run(args.idempotency_key, row.id);
      return result;
    } finally {
      bytes.fill(0);
    }
  }
  append(row, args) {
    if (!/^[A-Za-z0-9+/]+={0,2}$/.test(args.data))
      throw new BridgeError('Upload chunk must be canonical Base64');
    const bytes = Buffer.from(args.data, 'base64');
    try {
      if (
        !bytes.length ||
        bytes.length > UPLOAD_CHUNK_BYTES ||
        bytes.toString('base64') !== args.data
      )
        throw new BridgeError('Upload chunk exceeds its bound or is not canonical');
      return this.tx(() => {
        const current = this.row(row.id),
          metadata = this.open(current.payload, `upload:${row.id}`),
          digest = hash(bytes);
        const previous = this.db
          .prepare('SELECT digest FROM dotbridge_upload_chunks WHERE upload_id=? AND offset=?')
          .get(row.id, args.offset);
        if (previous) {
          if (previous.digest !== digest)
            throw new BridgeError('A different chunk occupies this offset', {
              code: -32013,
              status: 409,
            });
          return this.status(current);
        }
        if (
          current.state !== 'pending' ||
          args.offset !== current.received ||
          current.received + bytes.length > metadata.size
        )
          throw new BridgeError('Unexpected upload offset or size');
        const retained = this.db
          .prepare('SELECT coalesce(sum(length(payload)),0) AS n FROM dotbridge_upload_chunks')
          .get().n;
        const payload = this.seal(
          bytes.toString('base64'),
          `upload-chunk:${row.id}:${args.offset}`,
        );
        if (retained + Buffer.byteLength(payload) > 64 * 1024 * 1024)
          throw new BridgeError('Encrypted upload storage is full', { code: -32013, status: 429 });
        this.db
          .prepare('INSERT INTO dotbridge_upload_chunks VALUES (?,?,?,?)')
          .run(row.id, args.offset, payload, digest);
        this.db
          .prepare('UPDATE dotbridge_uploads SET received=received+? WHERE id=?')
          .run(bytes.length, row.id);
        return this.status(this.row(row.id));
      });
    } finally {
      bytes.fill(0);
    }
  }
}
